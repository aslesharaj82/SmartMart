package com.Logicalstatements;

public class Switchcases {

	public static void main(String[] args) {
		int a=0;
		switch (a) {
		case 0: 
			System.out.println("hello");
			break;
		case 1 :
			System.out.println("Hi");
		case 2:
			System.out.println("Aslesha");
			break;
			default :
				System.out.println("Nothing");
		}
		

	}

}
